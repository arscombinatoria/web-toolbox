    await expect(page.getByLabel('Payload', { exact: true })).toHaveValue(/<script>/);
    const header = await page.getByLabel('Header', { exact: true }).boundingBox();
    const payload = await page.getByLabel('Payload', { exact: true }).boundingBox();
